function scrollRelRow(rowId, dir) {
  const el = document.getElementById(rowId);
  if (!el) return;
  const cards = el.querySelectorAll('.rel-card');
  const wrapRect = el.getBoundingClientRect();
  const center = wrapRect.left + wrapRect.width / 2;
  cards.forEach(card => {
    const rect = card.getBoundingClientRect();
    const dist = (rect.left + rect.width / 2 - center) / (wrapRect.width / 2);
    const tilt = dir * -18 * (1 - Math.abs(dist) * 0.4);
    const scale = 1 - Math.abs(dist) * 0.08;
    card.style.transition = 'transform .45s cubic-bezier(.34,1.56,.64,1),opacity .45s ease';
    card.style.transform = `perspective(900px) rotateY(${tilt}deg) scale(${Math.max(scale,0.82)})`;
    card.style.opacity = Math.max(1 - Math.abs(dist) * 0.18, 0.55);
  });
  el.scrollBy({ left: dir * 276, behavior: 'smooth' });
  setTimeout(() => {
    cards.forEach(card => { card.style.transform = ''; card.style.opacity = ''; });
  }, 420);
}

