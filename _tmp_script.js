function addToCartQuick(productId) {
  const p = products.find(x => x.id === productId);
  if (!p) return;
  
  const cartItem = {
    id: p.id,
    name: p.name,
    price: p.price,
    basePrice: p.price,
    oldPrice: p.oldPrice,
    image: p.image,
    qty: 1,
    qtyLabel: '1 pc',
    qtyVal: 1,
    unit: 'piece'
  };
  
  const existing = JSON.parse(localStorage.getItem('cart') || '[]');
  const idx = existing.findIndex(i => String(i.id) === String(p.id));
  if (idx > -1) {
    existing[idx].qty += 1;
  } else {
    existing.push(cartItem);
  }
  
  localStorage.setItem('cart', JSON.stringify(existing));
  updateCounters();
  showToast('🛞 ' + p.name + ' added to cart!');
}

