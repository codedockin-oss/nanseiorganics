function loadProduct() {
  const params = new URLSearchParams(window.location.search);
  const urlId  = params.get('id');

  console.log('Loading product with ID:', urlId);

  if (!urlId) {
    console.log('No product ID found in URL');
    const legacy = parseInt(localStorage.getItem('selectedProduct'));
    if (legacy) { 
      console.log('Found legacy product ID:', legacy);
      window.location.replace('product.html?id=' + legacy); 
      return; 
    }
    // If no ID at all, redirect to index
    console.log('Redirecting to index.html');
    window.location.href = 'index.html';
    return;
  }

  const id = urlId || '1';

  console.log('Processing product ID:', id);

  // If it's a plain numeric ID, use static data directly — no API call needed
  const staticProduct = products.find(p => String(p.id) === String(id));
  if (staticProduct) {
    console.log('Found static product:', staticProduct.name);
    currentProduct = staticProduct;
    document.title = currentProduct.name + ' | NANSAI';
    try { render(); } catch(e) { console.error('render error', e); }
    try { renderRelated(); } catch(e) {}
    try { renderBlog(); } catch(e) {}
    try { updateCounters(); } catch(e) {}
    setTimeout(() => { if (typeof observeBlogCards === 'function') observeBlogCards(); }, 150);
    return;
  }

  console.log('Product not found in static data, trying API or fallback');
  // If product not found, use first product as fallback
  if (!staticProduct && products.length > 0) {
    console.log('Using fallback product:', products[0].name);
    currentProduct = products[0];
    // Update URL to match the fallback product
    const newUrl = new URL(window.location);
    newUrl.searchParams.set('id', products[0].id);
    window.history.replaceState(null, '', newUrl);
    
    document.title = currentProduct.name + ' | NANSAI';
    try { render(); } catch(e) { console.error('render error', e); }
    try { renderRelated(); } catch(e) {}
    try { renderBlog(); } catch(e) {}
    try { updateCounters(); } catch(e) {}
    setTimeout(() => { if (typeof observeBlogCards === 'function') observeBlogCards(); }, 150);
    return;
  }

  // Only hit the API for MongoDB _id strings (not found in static array)
  const base = window.API_BASE || 'http://localhost:5000/api';
  fetch(base + '/products/' + id)
    .then(r => r.json())
    .then(data => {
      if (data.success && data.product) {
        const p = data.product;
        currentProduct = {
          id:       p._id,
          name:     p.name,
          category: p.category,
          price:    p.price,
          oldPrice: p.oldPrice || Math.round(p.price * 1.25),
          rating:   p.rating || 4.5,
          reviews:  p.numReviews || 0,
          sold:     0,
          badge:    p.badge || 'new',
          image:    p.images?.[0]?.url || p.image || '',
          thumbs:   (p.images || []).slice(1).map(i => i.url || i),
          variants: ['Standard'],
          tagline:  p.tagline || '',
          desc:     p.description || '',
          specs:    { 'Origin': 'Tamil Nadu, India', 'Certification': 'FSSAI', 'Unit': p.unit || '', 'Weight': p.weight || '' },
          nutrition: {},
          reviewData: [],
        };
      } else {
        currentProduct = products[0];
      }
      document.title = currentProduct.name + ' | NANSAI';
      try { render(); } catch(e) { console.error('render error', e); }
      try { renderRelated(); } catch(e) {}
      try { renderBlog(); } catch(e) {}
      try { updateCounters(); } catch(e) {}
      setTimeout(() => { if (typeof observeBlogCards === 'function') observeBlogCards(); }, 150);
    })
    .catch(() => {
      currentProduct = products[0];
      document.title = currentProduct.name + ' | NANSAI';
      try { render(); } catch(e) {}
      try { renderRelated(); } catch(e) {}
      try { renderBlog(); } catch(e) {}
      try { updateCounters(); } catch(e) {}
      setTimeout(() => { if (typeof observeBlogCards === 'function') observeBlogCards(); }, 150);
    });
}

